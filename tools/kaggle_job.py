"""Run Tessa's fetch and search on Kaggle: pack files into one script, push it as a notebook, watch it, fetch its output.

The script carries the files as a base64 zip and runs one command, as the survey's notebooks did (tessa-fetch2,
tessa-search2). It talks to Kaggle's REST API on www.kaggle.com with KAGGLE_USERNAME/KAGGLE_KEY, or with credentials
a proxy adds.

  python tools/kaggle_job.py push SLUG --files a.txt pipeline/fetch.py --run pipeline/fetch.py --targets a.txt ...
         [--gpu] [--source OTHER_SLUG ...]          everything after --run is the command (python is implied)
  python tools/kaggle_job.py status SLUG
  python tools/kaggle_job.py output SLUG OUT_DIR    download the notebook's output files
"""
import argparse
import base64
import io
import json
import os
import sys
import time
import urllib.request
import zipfile
from pathlib import Path

API = "https://www.kaggle.com/api/v1"
USER = os.environ.get("KAGGLE_USERNAME", "braveai")
TEMPLATE = '''# Generated by tools/kaggle_job.py: unpacks the job folder and runs one command.
import base64, io, os, subprocess, sys, zipfile
SRC = "/kaggle/temp/src"  # /kaggle/src (where Kaggle puts this script) can be read-only
zipfile.ZipFile(io.BytesIO(base64.b64decode("{zip}"))).extractall(SRC)
os.environ["KAGGLE_INPUTS"] = "/kaggle/input"
if os.path.exists(f"{{SRC}}/requirements.txt"):
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-r", f"{{SRC}}/requirements.txt"], check=True)
os.chdir(SRC)
sys.exit(subprocess.call([sys.executable, "-u"] + {cmd!r}))
'''


def call(path: str, body: dict | None = None) -> dict:
    headers = {"Content-Type": "application/json", "User-Agent": "tessa-kaggle-job/1.0"}
    if os.environ.get("KAGGLE_KEY"):
        token = base64.b64encode(f"{USER}:{os.environ['KAGGLE_KEY']}".encode()).decode()
        headers["Authorization"] = f"Basic {token}"
    req = urllib.request.Request(f"{API}/{path}", json.dumps(body).encode() if body is not None else None, headers)
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.loads(r.read() or b"{}")


def pack(files: list[str], root: Path) -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            src, _, name = f.partition("=")  # path=name_in_zip, or just path
            z.write(root / src if not Path(src).is_absolute() else src, name or Path(src).as_posix())
    return base64.b64encode(buf.getvalue()).decode()


def push(slug: str, files: list[str], cmd: list[str], gpu: bool, sources: list[str], root: Path) -> dict:
    text = TEMPLATE.format(zip=pack(files, root), cmd=cmd)
    body = {"slug": f"{USER}/{slug}", "newTitle": slug, "text": text, "language": "python", "kernelType": "script",
            "isPrivate": True, "enableGpu": gpu, "enableTpu": False, "enableInternet": True,
            "datasetDataSources": [], "competitionDataSources": [], "modelDataSources": [],
            "kernelDataSources": [s if "/" in s else f"{USER}/{s}" for s in sources], "categoryIds": []}
    if gpu:
        body["machineShape"] = "NvidiaTeslaT4"
    return call("kernels/push", body)


def status(slug: str) -> dict:
    return call(f"kernels/status?userName={USER}&kernelSlug={slug}")


def output(slug: str, out: Path) -> list[str]:
    got = call(f"kernels/output?userName={USER}&kernelSlug={slug}")
    out.mkdir(parents=True, exist_ok=True)
    names = []
    for f in got.get("files", []):
        dest = out / f["fileName"]
        dest.parent.mkdir(parents=True, exist_ok=True)
        req = urllib.request.Request(f["url"], headers={"User-Agent": "tessa-kaggle-job/1.0"})
        with urllib.request.urlopen(req, timeout=600) as r:
            dest.write_bytes(r.read())
        names.append(f["fileName"])
    if got.get("log"):
        (out / "kaggle.log").write_text(got["log"], encoding="utf-8")
    return names


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("push")
    p.add_argument("slug")
    p.add_argument("--files", nargs="+", required=True, help="paths to pack (path=name renames it in the job)")
    p.add_argument("--gpu", action="store_true", help="2x T4")
    p.add_argument("--source", nargs="*", default=[], help="notebooks whose output this one reads")
    p.add_argument("--root", type=Path, default=Path.cwd())
    p.add_argument("--run", nargs=argparse.REMAINDER, required=True)
    s = sub.add_parser("status")
    s.add_argument("slug")
    o = sub.add_parser("output")
    o.add_argument("slug")
    o.add_argument("out", type=Path)
    a = ap.parse_args()
    if a.cmd == "push":
        print(json.dumps(push(a.slug, a.files, a.run, a.gpu, a.source, a.root), indent=1))
    elif a.cmd == "status":
        print(json.dumps(status(a.slug), indent=1))
    else:
        print("\n".join(output(a.slug, a.out)))


if __name__ == "__main__":
    main()
